    // ==================== getSyncStatus ====================

    @Test
    void getSyncStatus_withPendingSync_returnsCorrectly() {
        BookDraft draft = makeDraft(1L, 10L);
        draft.setSnapshotRevision(0L);
        when(bookDraftRepository.findById(1L)).thenReturn(Optional.of(draft));

        Publication pub = makePublication(10L, "Pub", 5L);
        when(publicationRepository.findById(10L)).thenReturn(Optional.of(pub));

        DraftSyncLog log = new DraftSyncLog();
        log.setPersonId("p1");
        log.setChangeType("updated");
        log.setAcknowledged(false);
        when(draftSyncLogRepository.findByDraftIdOrderByCreatedAtDesc(1L))
                .thenReturn(Arrays.asList(log));
        when(personRepository.findByPublicationIdAndPersonId(10L, "p1"))
                .thenReturn(Optional.of(makePerson(50L, 10L, "p1", "张三")));

        DraftSyncStatusResponse resp = publishingService.getSyncStatus(1L);

        assertEquals(1L, resp.getDraftId());
        assertEquals(5L, resp.getCurrentRevision());
        assertEquals(0L, resp.getSnapshotRevision());
        assertTrue(resp.isHasPendingSync());
        assertEquals(1, resp.getChanges().size());
        assertEquals("p1", resp.getChanges().get(0).getPersonId());
        assertEquals("张三", resp.getChanges().get(0).getPersonName());
        assertEquals("updated", resp.getChanges().get(0).getChangeType());
        assertFalse(resp.getChanges().get(0).isAcknowledged());
    }

