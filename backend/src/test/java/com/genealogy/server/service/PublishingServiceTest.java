    @Test
    void saveSheets_replacesAndSavesSheets() {
        BookDraft draft = makeDraft(1L, 10L);
        when(bookDraftRepository.findById(1L)).thenReturn(Optional.of(draft));

        SheetSaveRequest req1 = new SheetSaveRequest();
        req1.setSheetNumber(1);
        req1.setSheetType("genealogy");
        req1.setLayoutData("{\"cols\":12}");

        SheetSaveRequest req2 = new SheetSaveRequest();
        req2.setSheetNumber(2);
        req2.setSheetType("index");
        req2.setLayoutData("{\"cols\":6}");

        BookSheet saved1 = makeSheet(100L, 1L, 1);
        saved1.setSheetType("genealogy");
        BookSheet saved2 = makeSheet(101L, 1L, 2);
        saved2.setSheetType("index");
        when(bookSheetRepository.save(any(BookSheet.class)))
                .thenReturn(saved1)
                .thenReturn(saved2);

        List<SheetResponse> results = publishingService.saveSheets(1L, Arrays.asList(req1, req2));

        assertEquals(2, results.size());
        assertEquals("genealogy", results.get(0).getSheetType());
        assertEquals("index", results.get(1).getSheetType());

        // Old sheets should be deleted first
        verify(bookSheetRepository).deleteByDraftId(1L);
        verify(bookSheetRepository, times(2)).save(any(BookSheet.class));
    }

