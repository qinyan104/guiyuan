    // ==================== createDraft ====================

    @Test
    void createDraft_savesDraftAndReturnsResponse() {
        Long userId = 1L;
        BookDraftRequest req = new BookDraftRequest();
        req.setPublicationId(10L);
        req.setTitle("My Draft");
        req.setSubtitle("subtitle");
        req.setPreface("pref");
        req.setEpilogue("epi");
        req.setStyleConfig("{\"color\":\"red\"}");

        BookDraft saved = makeDraft(100L, 10L);
        saved.setTitle("My Draft");
        when(bookDraftRepository.save(any(BookDraft.class))).thenReturn(saved);
        // toResponse calls these
        when(bookSheetRepository.countByDraftId(100L)).thenReturn(0L);
        when(publicationRepository.findById(10L)).thenReturn(
                Optional.of(makePublication(10L, "Pub", 5L)));

        BookDraftResponse resp = publishingService.createDraft(userId, req);

        assertNotNull(resp);
        assertEquals(100L, resp.getId());
        assertEquals("My Draft", resp.getTitle());
        assertEquals(10L, resp.getPublicationId());

        ArgumentCaptor<BookDraft> captor = ArgumentCaptor.forClass(BookDraft.class);
        verify(bookDraftRepository).save(captor.capture());
        BookDraft captured = captor.getValue();
        assertEquals("draft", captured.getStatus());
        assertEquals(1, captured.getVersion());
        assertEquals(0L, captured.getSnapshotRevision());
        assertEquals(userId, captured.getCreatedBy());
        assertEquals(userId, captured.getUpdatedBy());
    }

